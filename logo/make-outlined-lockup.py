#!/usr/bin/env python3
"""Generate the web lockups: thalamic-lockup-{light,dark}-bg-web.svg.

The delivered thalamic-lockup-*.svg set "thalamic." as live <text> in Inter
Medium. Inter is neither a system font on macOS/Windows nor loaded by the site,
so as an <img> the wordmark silently falls back to Helvetica/Arial and both the
letterforms and the advance width change per platform. This converts the glyphs
to outlines, which makes the file self-contained and pixel-identical anywhere,
and trims the viewBox to the ink (the delivered file leaves ~28% of its width
as trailing whitespace after the wordmark, which is a layout hazard in flex).

The mark geometry, the text position/size/tracking and both colourways are
copied from the delivered files unchanged — only the <text> becomes <path>.

Usage:
    curl -o inter500.ttf 'https://fonts.gstatic.com/s/inter/v20/UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuI6fMZg.ttf'
    python make-outlined-lockup.py inter500.ttf     # the URL is Google Fonts'
                                                    # css2 src for Inter wght 500

Verified by rendering the delivered lockup in headless Chrome with the real
Inter webfont and pixel-diffing against the output: the only difference is a
1px antialiasing hairline at the glyph edges (text and path rasterisation
differ), with no positional or kerning shift.
"""
import sys
from fontTools.misc.transform import Transform
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

# --- values lifted verbatim from the delivered lockup -----------------------
TEXT, STOP = "thalamic", "."
X, BASELINE, SIZE, TRACKING = 68.0, 41.0, 26.0, 0.3
# the mark's ticks span 9..55 with a 1.6 round-capped stroke, so its ink
# reaches 0.8 beyond each end
MARK_MIN, MARK_MAX = 9.0 - 0.8, 55.0 + 0.8

font = TTFont(sys.argv[1])
scale = SIZE / font["head"].unitsPerEm
cmap, hmtx, glyphs = font.getBestCmap(), font["hmtx"], font.getGlyphSet()


def kern_pairs():
    """Flat (left, right) -> x-advance map from GPOS pair positioning."""
    out = {}
    if "GPOS" not in font:
        return out
    for lookup in font["GPOS"].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            sub = getattr(sub, "ExtSubTable", sub)
            if sub.__class__.__name__ != "PairPos":
                continue
            if sub.Format == 1:
                for left, ps in zip(sub.Coverage.glyphs, sub.PairSet):
                    for rec in ps.PairValueRecord:
                        if getattr(rec.Value1, "XAdvance", 0):
                            out[(left, rec.SecondGlyph)] = rec.Value1.XAdvance
            elif sub.Format == 2:
                c2 = sub.ClassDef2.classDefs
                for left in sub.Coverage.glyphs:
                    rec1 = sub.Class1Record[sub.ClassDef1.classDefs.get(left, 0)]
                    for right, j in c2.items():
                        v = getattr(rec1.Class2Record[j].Value1, "XAdvance", 0)
                        if v:
                            out[(left, right)] = v
    return out


KERN = kern_pairs()
bounds = BoundsPen(glyphs)


def run(text, pen_x):
    """Outline a run of characters; return (path data, pen x after the run)."""
    parts, prev = [], None
    for ch in text:
        name = cmap[ord(ch)]
        if prev is not None:
            pen_x += KERN.get((prev, name), 0) * scale
        xform = Transform(scale, 0, 0, -scale, pen_x, BASELINE)
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        glyphs[name].draw(TransformPen(pen, xform))
        glyphs[name].draw(TransformPen(bounds, xform))
        if pen.getCommands():
            parts.append(pen.getCommands())
        pen_x += hmtx[name][0] * scale + TRACKING
        prev = name
    return " ".join(parts), pen_x


word_d, x_after = run(TEXT, X)
stop_d, _ = run(STOP, x_after)

# trim to the ink of mark + wordmark
x0, y0 = MARK_MIN, MARK_MIN
x1 = max(MARK_MAX, bounds.bounds[2])
y1 = MARK_MAX
view = f"{x0:g} {y0:g} {x1 - x0:.2f} {y1 - y0:.2f}"

# The delivered lavender (#9184d9) was replaced by the site accent on request,
# so the lockup's period matches the accent period in the page headlines. Light
# and dark colourways take --accent and --accent-lift respectively, the same
# split the stylesheet uses.
ACCENT_LIGHT = "#2b4bad"
ACCENT_DARK = "#6f94ee"

TEMPLATE = '''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="{w:.0f}" height="{h:.0f}" fill="none">
  <!-- GENERATED by make-outlined-lockup.py from thalamic-lockup-{suffix}.svg —
       same geometry, recoloured to the site accent, with "thalamic." (Inter
       Medium 26 / 0.3 tracking) outlined and the viewBox trimmed to the ink. -->
  <g stroke="{accent}" stroke-width="1.6" stroke-linecap="round">
    <rect x="15" y="15" width="34" height="34" rx="7"></rect>
    <path d="M9 24h6M9 32h6M9 40h6M49 24h6M49 32h6M49 40h6M24 9v6M32 9v6M40 9v6M24 49v6M32 49v6M40 49v6"></path>
  </g>
  <polyline points="21,33 26,33 29,23 33,43 36,27 38,33 43,33" stroke="{trace}" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" fill="none"></polyline>
  <path fill="{trace}" d="{word}"></path>
  <path fill="{accent}" d="{stop}"></path>
</svg>
'''

for suffix, trace, accent in (("light-bg", "#161826", ACCENT_LIGHT),
                              ("dark-bg", "#e9e9ed", ACCENT_DARK)):
    out = f"thalamic-lockup-{suffix}-web.svg"
    with open(out, "w") as fh:
        fh.write(TEMPLATE.format(view=view, w=(x1 - x0) * 4, h=(y1 - y0) * 4,
                                 suffix=suffix, trace=trace, accent=accent,
                                 word=word_d, stop=stop_d))
    print(f"wrote {out}  viewBox='{view}'", file=sys.stderr)
